ASSUME CS:CODE, DS:DATA
DATA SEGMENT
LIST DB 01H,02H,03H,04H,05H
COUNT DB 05H
RES DW  0H
DATA ENDS
CODE SEGMENT
START:
MOV AX, DATA
MOV DS, AX
MOV AX,0H
MOV BX,0H
MOV DX,0H
MOV CL,COUNT
LEA SI,LIST
LEA DI,LIST
GO: 
MOV AL,[SI]
MOV BL,[SI]
MUL BL
INC SI
ADD DX,AX
DEC CL
JNZ GO
MOV RES,DX
INT 03H
CODE ENDS
END START