ASSUME CS:CODE, DS:DATA
DATA SEGMENT
LIST DB 04H,0AH,01H,21H,09H
LARG  DB  0H
DATA ENDS
CODE SEGMENT
START:
MOV AX, DATA
MOV DS, AX
MOV AX,0H
MOV CL,04
LEA SI,LIST
MOV AL,[SI]
L2: 
CMP AL,[SI+1]
JNC L1
MOV AL,[SI+1]
L1:
INC SI
DEC CL
JNZ L2
MOV LARG,AL
INT 03H
CODE ENDS
END START